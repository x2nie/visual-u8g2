import { loadFile, mount, reactive, whenReady } from "@odoo/owl";
import App from './App'
import { nokia5110 } from "./displays/Displays";

whenReady(async function () {

  const [templates, cpp_content] = await Promise.all([
    loadFile("templates.xml"),

    // loadFile("examples/intro.raw.cpp"),
    loadFile("examples/dev1.cpp"),
  ])

  const env = {
    editor: reactive({
              content: cpp_content,
            }),
    sim: reactive({
          display_name: nokia5110.name,
          scale:5,
          layers: [], //generated by loop are duplicated
          lines: [], //layers, unique per-line-number
          })
  }

  mount(App, document.body, { 
      env, 
      templates, 
      // 'debug': true,
      //props: {...}, templates: "..."}
  });
  
})
